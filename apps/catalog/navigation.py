"""Порядок разделов в сайдбаре каталога.

Категории приходят от поставщиков со своим служебным `order`, и в дереве они
выстраивались как попало: сверху оказывались котлы и вентустановки, а
кондиционеры — где-то в середине (замечание владельца 2026-08-29). Поэтому
порядок и группировка заданы здесь, а не в данных: список читается как
витрина, а не как выгрузка.

Категории, которых нет в списке, показываются последней группой «Другое» —
так новый раздел от поставщика не потеряется, но и не сломает порядок.
"""

CATALOG_GROUPS = [
    ('Кондиционеры', [
        'Бытовые сплит-системы',
        'Полупромышленные сплит-системы',
        'Мобильные кондиционеры',
        'Оконные кондиционеры',
    ]),
    ('Обогрев', [
        'Конвекторы',
        'Тепловые пушки',
        'Тепловентиляторы',
        'Масляные радиаторы',
        'Инфракрасные обогреватели',
        'Тепловые завесы',
    ]),
    ('Отопление и горячая вода', [
        'Отопительные котлы',
        'Радиаторы отопления',
        'Тёплый пол',
        'Накопительные водонагреватели',
        'Проточные водонагреватели',
    ]),
    ('Вентиляция и воздух', [
        'Бытовые вентиляционные установки',
        'Компактные моноблочные вентиляционные установки',
        'Рекуператоры',
        'Бытовые вентиляторы',
        'Бытовые увлажнители воздуха',
        'Бытовые осушители воздуха',
        'Воздухоочистители',
    ]),
]

# Плоский порядок для сортировки: title → позиция
CATEGORY_ORDER = {
    title: position
    for position, title in enumerate(
        title for _, titles in CATALOG_GROUPS for title in titles
    )
}


def group_categories(categories):
    """[(название группы, [категории])] в порядке CATALOG_GROUPS.

    `categories` — уже отфильтрованный queryset/список. Пустые группы
    не возвращаются, чтобы в сайдбаре не висели заголовки без содержимого.
    """
    by_title = {c.title: c for c in categories}
    used = set()
    groups = []

    for group_title, titles in CATALOG_GROUPS:
        items = [by_title[t] for t in titles if t in by_title]
        used.update(c.title for c in items)
        if items:
            groups.append((group_title, items))

    rest = [c for c in categories if c.title not in used]
    if rest:
        groups.append(('Другое', sorted(rest, key=lambda c: c.title)))
    return groups
